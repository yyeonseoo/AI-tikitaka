"""Reaction yield, plan 12 (reaction/README.md, "12차 계획"), two checks with the final SM model (plan 6 LightGBM, F1):
A. Yield MAE on SM leave-one-electrophile-out (7 groups) vs condition average, ridge·F1 and one-hot pair linear,
   so report 4.1 uses the final configuration instead of the plan 2 tuned model.
B. Plan 5 sequential optimisation (warm, greedy) started from the model's top 4 instead of 4 random picks (as the demo
   does); compared with the cached random-start runs. Deterministic, so one run per pair.
Usage: python reaction/model12.py   (-> reaction/results_model12.md)"""
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from threadpoolctl import threadpool_limits

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from eda import md  # noqa: E402
from model import boot_ci, fmt, ridge_pairs  # noqa: E402
from model2 import desc_sm  # noqa: E402
from model5 import BATCH, CACHE5, COND, N0, PAIR, ROUNDS, bayes_linear, judge, lgbm_ensemble, trace_metrics  # noqa: E402
from model6 import ridge_f1  # noqa: E402
from prepare import SM_SLOTS, load_sm  # noqa: E402

OUT = ROOT / "results_model12.md"


def fold_a(XF, XR, y, grp, d, g):
    threadpool_limits(1)
    hist, target = np.flatnonzero(grp != g), np.flatnonzero(grp == g)
    m = d.iloc[hist].groupby(COND).y.mean()
    ap = d.iloc[target]
    cm = ap[COND].merge(m.rename("m"), how="left", left_on=COND, right_index=True).m.to_numpy()
    m2 = ap[COND[:2]].merge(d.iloc[hist].groupby(COND[:2]).y.mean().rename("m"), how="left", left_on=COND[:2], right_index=True).m.to_numpy()
    cm = np.where(np.isnan(cm), m2, cm)  # conditions unseen in history (1e solvent set) -> ligand x base mean, as model5
    P = {"조건 평균": cm,
         "능형 회귀 + 분자 표현": ridge_f1(XF, y, grp, hist, target)[0],
         "상호작용 선형 모델": np.clip(bayes_linear(XR[hist], y[hist], XR[target], "warm")[0], 0, 100),
         "LightGBM + 분자 표현": np.clip(lgbm_ensemble(XF[hist], y[hist], XF[target], "warm")[0], 0, 100)}
    return g, {k: float(np.abs(v - y[target]).mean()) for k, v in P.items()}


def run_b(X, y, hist, target):
    """Plan 5 greedy loop, first batch = model top 4 from history only."""
    threadpool_limits(1)
    done = []
    for _ in range(ROUNDS + 1):
        rest = np.setdiff1d(target, done)
        trn = np.concatenate([hist, done]).astype(int)
        mu = lgbm_ensemble(X[trn], y[trn], X[rest], "warm")[0]
        done += list(rest[np.argsort(-mu, kind="stable")[:N0 if not done else BATCH]])
    return np.array(done)


def main():
    t0 = time.time()
    d = load_sm()
    y = d.y.to_numpy(float)
    XF, XR = desc_sm(d).to_numpy(float), ridge_pairs(d, SM_SLOTS).to_numpy(float)

    # A
    grp = d.electrophile.to_numpy()
    A = dict(Parallel(n_jobs=-1)(delayed(fold_a)(XF, XR, y, grp, d, g) for g in pd.unique(grp)))
    TA = pd.DataFrame(A).T
    lg = "LightGBM + 분자 표현"
    rows_a = [{"모델": m, "MAE (%p)": fmt(boot_ci(TA[m]))} for m in TA.columns]
    va = [{"비교": f"{lg} − {b}", "MAE 차이 (%p, 음수 = LightGBM이 좋음)": fmt(boot_ci(TA[lg] - TA[b]), True), "결과": judge(boot_ci(TA[lg] - TA[b]))}
          for b in TA.columns if b != lg]
    per_a = TA.round(2).reset_index().rename(columns={"index": "제외한 친전자체"})

    # B
    key = d[PAIR].agg(" + ".join, axis=1).to_numpy()
    pairs = list(pd.unique(key))
    runs = Parallel(n_jobs=-1)(delayed(run_b)(XF, y, np.flatnonzero(key != p), np.flatnonzero(key == p)) for p in pairs)
    rows_b = []
    for i, (p, r) in enumerate(zip(pairs, runs)):
        best = y[key == p].max()
        top = trace_metrics(y[r][None, :], best)
        rnd = trace_metrics(pickle.loads((CACHE5 / f"warm_LightGBM_k0_{i}.pkl").read_bytes()), best)
        rows_b.append({"pair": p, **{f"상위 4개 시작 {c}": top[c] for c in ("regret@8", "regret@20", "발견까지 실험 수")},
                       **{f"무작위 4개 시작 {c}": rnd[c] for c in ("regret@8", "regret@20", "발견까지 실험 수")}})
    TB = pd.DataFrame(rows_b)
    sb = [{"시작 방식": s, "regret@8": f"{TB[f'{s} regret@8'].mean():.2f}", "regret@20": fmt(boot_ci(TB[f"{s} regret@20"])),
           "발견까지 실험 수": f"{TB[f'{s} 발견까지 실험 수'].mean():.2f}"} for s in ("무작위 4개 시작", "상위 4개 시작")]
    vb = [{"지표": c, "상위 4개 − 무작위 4개 시작": fmt(boot_ci(TB[f"상위 4개 시작 {c}"] - TB[f"무작위 4개 시작 {c}"]), True),
           "결과": judge(boot_ci(TB[f"상위 4개 시작 {c}"] - TB[f"무작위 4개 시작 {c}"]))} for c in ("regret@20", "발견까지 실험 수")]

    OUT.write_text(
        "# 반응 수율 12차 결과: 최종 모델 설정으로 두 가지 확인 (generated by reaction/model12.py)\n\n"
        f"실행 {(time.time() - t0) / 60:.0f}분.\n\n"
        "## A. SM 처음 보는 친전자체의 수율 예측 (친전자체 7종 하나 빼기, 구간은 7그룹 부트스트랩)\n"
        f"{md(pd.DataFrame(rows_a), index=False)}\n\n{md(pd.DataFrame(va), index=False)}\n\n"
        f"그룹별 MAE\n{md(per_a, index=False)}\n\n"
        "## B. 순차 최적화 시작 방식 (과거 데이터 있음, 탐욕, 15쌍)\n"
        "무작위 4개 시작 = 5차 결과(시드 10개 평균). 상위 4개 시작 = 첫 배치를 과거 14쌍만으로 학습한 모델의 상위 4개로 고름(결정적, 쌍마다 1회).\n\n"
        f"{md(pd.DataFrame(sb), index=False)}\n\n{md(pd.DataFrame(vb), index=False)}\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
