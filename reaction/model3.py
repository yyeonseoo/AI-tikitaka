"""Reaction yield, plan 3 (reaction/README.md, "3차 계획"): Buchwald-Hartwig with a whole arene held out.
Each outer fold holds out one of the 5 arenes (its Cl, Br and I substrates); settings are chosen by leave-one-arene-out
inside the 4 training arenes. Same models, settings search and checkpoints as model2.py.
Usage: python reaction/model3.py [--mlp]   (-> reaction/results_model3.md)"""
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import r2_score

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from eda import md  # noqa: E402
from model import boot_ci, fmt, per_group_mae  # noqa: E402
from model2 import desc_bh, knowledge_bh, run_split, within_group  # noqa: E402
from prepare import BH_SLOTS, load_bh  # noqa: E402

OUT = ROOT / "results_model3.md"
NAME = "BH 처음 보는 고리"
ARENE = {"*c1ccc(C(F)(F)F)cc1": "4-CF₃-페닐", "*c1ccc(CC)cc1": "4-에틸페닐", "*c1ccc(OC)cc1": "4-메톡시페닐",
         "*c1ccccn1": "2-피리딜", "*c1cccnc1": "3-피리딜"}


def main():
    t0 = time.time()
    d = load_bh()
    pred, chosen = run_split(NAME, d, BH_SLOTS, "arene", desc_bh(d), knowledge_bh(d))
    unit = "aryl_halide"  # bootstrap over the 15 held-out substrates (only 5 arenes)
    rows = []
    for k, p in pred.items():
        W = within_group(d, p, unit)
        rows.append({"방법": k, "MAE (%p)": fmt(boot_ci(per_group_mae(d, p, unit))), "R²": round(r2_score(d.y, p), 3),
                     "출발물질 안 순위 상관": round(W.rho.mean(), 3),
                     "1순위 추천 실제 수율": f"{W.top1.mean():.1f}% (최고 {W.best.mean():.1f}%, 평균 {W['mean'].mean():.1f}%)"})
    by_arene = pd.DataFrame({k: pd.Series(np.abs(p - d.y.to_numpy())).groupby(d.arene.map(ARENE).to_numpy()).mean().round(1)
                             for k, p in pred.items()})

    def judge(t):
        return "충족" if t[2] < 0 else ("우열 판단 증거 부족" if t[1] <= 0 <= t[2] else "반대 방향")
    V = [("주", "LGBM·F1 (주)", "최선 단순 (안쪽 검증 선택)"), ("화학 지식", "LGBM·F1+K", "LGBM·F1 (주)"),
         ("참고", "LGBM·F1+K+단조", "LGBM·F1+K")]
    if "MLP·F1+K (참고)" in pred:
        V.append(("참고", "MLP·F1+K (참고)", "최선 단순 (안쪽 검증 선택)"))
    vt = "## 판정\n| 구분 | 비교 | MAE 차이 (%p, 음수 = 앞이 좋음) | 결과 |\n|---|---|---|---|\n"
    for lab, a, b in V:
        t = boot_ci(per_group_mae(d, pred[a], unit) - per_group_mae(d, pred[b], unit))
        vt += f"| {lab} | {a} − {b} | {fmt(t, True)} | **{judge(t)}** |\n"
    OUT.write_text(f"# 반응 수율 3차 결과: 처음 보는 고리 (generated by reaction/model3.py)\n\n"
                   f"고리 5종을 하나씩 통째로 시험으로 빼고(출발물질 3종씩), 나머지 4종 고리로 학습. 설정은 고리 하나 빼기 검증으로 선택. "
                   f"구간은 시험 출발물질 15종 단위 부트스트랩. 실행 {(time.time() - t0) / 60:.0f}분.\n\n"
                   + vt + f"\n## 방법별\n{md(pd.DataFrame(rows), index=False)}\n\n## 고리별 MAE (%p)\n{md(by_arene)}\n\n"
                   + f"## 묶음마다 안쪽 검증 MAE와 고른 단순 기준선\n{md(chosen, index=False)}\n", encoding="utf-8")
    print(vt)


if __name__ == "__main__":
    main()
