"""Reaction yield, plan 10: how much history does the SM recommender need? (learning curve)
For each of the 15 (electrophile, nucleophile) pairs, train the plan 6 LightGBM on k randomly chosen other pairs
(k = 1, 2, 4, 7, 10, 14; 5 draws per k, 1 for k = 14), rank its 384 conditions with no experiment in the target pair,
and count experiments until a near-optimal condition (within 5%p of the best) when following that order.
Compared with random order and with the history-average order built from the same k pairs. Bootstrap over 15 pairs.
Usage: python reaction/model10.py   (-> reaction/results_model10.md)"""
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from threadpoolctl import threadpool_limits

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from eda import md  # noqa: E402
from model import boot_ci, fmt  # noqa: E402
from model2 import desc_sm  # noqa: E402
from model5 import COND, NEAR, PAIR, judge, lgbm_ensemble  # noqa: E402
from prepare import load_sm  # noqa: E402

OUT = ROOT / "results_model10.md"
KS, DRAWS = [1, 2, 4, 7, 10, 14], 5


def first_near(y_ordered, best):
    return int(np.argmax(y_ordered >= best - NEAR)) + 1


def random_first_near(yp):
    m = int((yp >= yp.max() - NEAR).sum())
    return (len(yp) + 1) / (m + 1)  # expected position of the first of m hits in a random order


def one(d, X, y, key, p, k, draw):
    threadpool_limits(1)
    others = [q for q in pd.unique(key) if q != p]
    hist_pairs = np.random.default_rng(1000 * draw + k).choice(others, k, replace=False) if k < len(others) else others
    hist, target = np.isin(key, hist_pairs), key == p
    yp, best, tie = y[target], y[target].max(), np.random.default_rng(draw).random(target.sum())
    q = lgbm_ensemble(X[hist], y[hist], X[target], "warm")[0]
    m = d[hist].groupby(COND).y.mean()  # same 384 conditions in every pair, so no fallback needed
    h = d.loc[target, COND].merge(m.rename("m"), how="left", left_on=COND, right_index=True).m.fillna(0).to_numpy()
    lg, hi = yp[np.lexsort((tie, -q))], yp[np.lexsort((tie, -h))]
    return {"pair": p, "k": k, "draw": draw, "n_hist": int(hist.sum()), "LightGBM": first_near(lg, best),
            "과거 평균 순서": first_near(hi, best), "무작위": random_first_near(yp),
            "LightGBM hit@20": float(lg[:20].max() >= best - NEAR), "과거 평균 hit@20": float(hi[:20].max() >= best - NEAR)}


def main():
    t0 = time.time()
    d = load_sm()
    y, key, X = d.y.to_numpy(float), d[PAIR].agg(" + ".join, axis=1).to_numpy(), desc_sm(d).to_numpy(float)
    jobs = [(p, k, r) for p in pd.unique(key) for k in KS for r in range(1 if k == 14 else DRAWS)]
    T = pd.DataFrame(Parallel(n_jobs=-1)(delayed(one)(d, X, y, key, *j) for j in jobs))
    P = T.groupby(["k", "pair"]).mean(numeric_only=True).reset_index()  # average draws first: pair is the unit

    rows, verdict = [], []
    for k, g in P.groupby("k"):
        rows.append({"과거 쌍 수": k, "과거 반응 수": f"{g.n_hist.mean():,.0f}",
                     "무작위": f"{g['무작위'].mean():.1f}", "과거 평균 순서": f"{g['과거 평균 순서'].mean():.1f}",
                     "LightGBM": fmt(boot_ci(g.LightGBM)),
                     "무작위 대비 감소": f"{1 - g.LightGBM.mean() / g['무작위'].mean():.0%}",
                     "LightGBM hit@20": f"{g['LightGBM hit@20'].mean():.0%}", "과거 평균 hit@20": f"{g['과거 평균 hit@20'].mean():.0%}"})
        for b in ("무작위", "과거 평균 순서"):
            t = boot_ci((g.LightGBM - g[b]).to_numpy())
            verdict.append({"과거 쌍 수": k, "비교": f"LightGBM − {b}", "차이 (실험 수, 음수 = LightGBM이 적음)": fmt(t, True), "결과": judge(t)})

    OUT.write_text(
        "# 반응 수율 10차 결과: 과거 데이터 양에 따른 SM 추천 성능 (generated by reaction/model10.py)\n\n"
        f"목표 쌍 15개. 쌍마다 다른 쌍 k개를 무작위로 골라(k별 {DRAWS}회, k = 14는 1회) 6차 LightGBM을 학습하고, 목표 쌍의 실험 없이 "
        f"384개 조건 순위를 매김. '실험 수' = 그 순서대로 실험할 때 준최적 조건(최고와 {NEAR:g}%p 이내)을 처음 만나는 순번. "
        f"무작위는 기댓값. 구간은 15쌍 단위 부트스트랩 1,000회. 실행 {(time.time() - t0) / 60:.0f}분.\n\n"
        f"## 과거 데이터 양별 (15쌍 평균, 준최적 조건까지 실험 수)\n{md(pd.DataFrame(rows), index=False)}\n\n"
        f"## 판정\n{md(pd.DataFrame(verdict), index=False)}\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
